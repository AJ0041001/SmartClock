/**
  * @brief This function handles Hard fault interrupt.
  */
/* Referenced directly from the naked assembly exception veneer below, so this
   function must have a link-visible symbol (it cannot be static). */
void HardFault_C_Handler(uint32_t *stacked, uint32_t exc_return)
{
  extern volatile uint32_t bsp_hardfault_cfsr;
  extern volatile uint32_t bsp_hardfault_hfsr;
  extern volatile uint32_t bsp_hardfault_mmfar;
  extern volatile uint32_t bsp_hardfault_bfar;
  extern volatile uint32_t bsp_hardfault_pc;
  extern volatile uint32_t bsp_hardfault_lr;
  extern volatile uint32_t bsp_hardfault_sp;
  extern volatile uint32_t bsp_hardfault_xpsr;
  extern volatile uint32_t bsp_hardfault_exc_return;
  uint32_t *core_frame = stacked;

  /* EXC_RETURN bit 4 clear means the FPU's extended frame (S0-S15, FPSCR,
     reserved = 18 words) precedes the normal R0-R3/R12/LR/PC/xPSR frame. */
  if ((exc_return & 0x10U) == 0U)
  {
    core_frame += 18U;
  }

  /* Store the fault status and the CPU's automatically stacked registers for
     Keil Watch.  Do not print or call HAL/FreeRTOS from an exception. */
  bsp_hardfault_cfsr = SCB->CFSR;
  bsp_hardfault_hfsr = SCB->HFSR;
  bsp_hardfault_mmfar = SCB->MMFAR;
  bsp_hardfault_bfar = SCB->BFAR;
  bsp_hardfault_sp = (uint32_t)stacked;
  bsp_hardfault_exc_return = exc_return;
  bsp_hardfault_lr = core_frame[5];
  bsp_hardfault_pc = core_frame[6];
  bsp_hardfault_xpsr = core_frame[7];

  while (1)
  {
  }
}

void HardFault_Handler(void) __attribute__((naked));
void HardFault_Handler(void)
{
  __asm volatile(
    "tst lr, #4      \n"
    "ite eq          \n"
    "mrseq r0, msp   \n"
    "mrsne r0, psp   \n"
    "mov r1, lr      \n"
    "b HardFault_C_Handler \n"
  );
}

